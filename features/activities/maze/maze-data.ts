// The standalone game also had a «Вільний» mode with unlimited lives and no
// end. A class activity has to finish, so only the two campaign modes ship.
export const MAZE_MODES: Record<string, MazeMode> = {
  beginner: {
    key: 'beginner',
    label: 'Початківець',
    wallInset: 10,
    hitboxScale: 0.62,
    starsPerLevel: 2,
    levels: BEGINNER_LEVELS,
  },
  master: {
    key: 'master',
    label: 'Майстер',
    wallInset: 4,
    hitboxScale: 1.0,
    starsPerLevel: 3,
    levels: MASTER_LEVELS,
  },
}

// Own-property check, not a plain lookup: 'constructor' and friends would
// otherwise resolve through Object.prototype and pass as a mode.
export function mazeMode(level: string): MazeMode | null {
  return Object.prototype.hasOwnProperty.call(MAZE_MODES, level) ? MAZE_MODES[level]! : null
}
