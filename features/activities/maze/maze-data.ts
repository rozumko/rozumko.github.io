// Level sets for «Чарівний лабіринт», ported from the standalone game.
// Every level is a 15×10 grid of characters:
//   '1' wall, '0' open floor, 'S' start (exactly one), 'E' cup / finish.
//
// The source data had four rows in master level 3 that were 16 characters
// long. The original engine read only the first COLS characters, so trimming
// them to 15 here preserves the level exactly as children played it.

export const MAZE_COLS = 15
export const MAZE_ROWS = 10
/** Logical size of one cell; the canvas scales the whole board to fit. */
export const MAZE_CELL = 40

export interface MazeMode {
  key: string
  label: string
  /** Wall inset in logical px — a smaller inset makes corridors tighter. */
  wallInset: number
  /** Multiplier on the player hitbox — below 1 forgives near misses. */
  hitboxScale: number
  starsPerLevel: number
  levels: readonly (readonly string[])[]
}

