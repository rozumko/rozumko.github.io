export type Difficulty = 'easy' | 'medium' | 'hard'
export type WordsMode = 'words' | 'sentences'

/** Apostrophes do not add a key press worth counting towards word length. */
function bareLength(word: string): number {
  return word.replace(/'/g, '').length
}

const WORD_POOLS: Record<Difficulty, readonly string[]> = {
  easy: WORDS.filter(word => bareLength(word) <= 5),
  medium: WORDS.filter(word => bareLength(word) >= 6 && bareLength(word) <= 8),
  hard: WORDS.filter(word => bareLength(word) >= 9),
}

/** How many items one round asks for. Sentences are far longer than words. */
export const ROUND_SIZE: Record<WordsMode, number> = { words: 18, sentences: 5 }

export interface WordsLevel {
  mode: WordsMode
  difficulty: Difficulty
  items: readonly string[]
}

/** `words-easy` → the short-word pool. Unknown ids fall back to the easiest. */
export function resolveWordsLevel(level: string): WordsLevel {
  const [rawMode, rawDifficulty] = level.split('-')
  const mode: WordsMode = rawMode === 'sentences' ? 'sentences' : 'words'
  const difficulty: Difficulty = rawDifficulty === 'medium' || rawDifficulty === 'hard' ? rawDifficulty : 'easy'
  return {
    mode,
    difficulty,
    items: mode === 'sentences' ? SENTENCES[difficulty] : WORD_POOLS[difficulty],
  }
}

