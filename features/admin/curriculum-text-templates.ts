/**
 * The prompt for ChatGPT, Claude or Gemini: the author attaches a lesson in
 * any form and pastes the answer into «Створити урок». Answers are taken only
 * from the material; the parser refuses a task without a marked answer anyway.
 */
export const LESSON_TEXT_PROMPT = `Перепиши доданий урок (HTML, документ Word або конспект) у текстовий формат уроку платформи Розумко. Поверни лише текст уроку — без пояснень і без блоку коду.

Формат:
1. Перший рядок — назва уроку. Далі рядки «Клас: N» і «Тривалість: N хв», потім «Цілі:» і цілі списком «- …».
2. Нотатки для вчителя про весь урок (обладнання, форма роботи, на що звернути увагу) напиши звичайними рядками після цілей, до першого кроку.
3. Кожен крок уроку починається рядком «## Назва кроку». Перерва — крок «## ☕ Перерва».
4. Зберігай порядок і дослівні тексти для учнів. Нічого не скорочуй і не вигадуй.
5. Кожен абзац — окремий рядок. Списки — рядками «- …» або «1. …». Таблиця — рядками «| A | B |», перший рядок — заголовки.
6. Жирний текст — **так**. Курсив, HTML, CSS і емодзі-оформлення блоків не використовуй.
7. Рядок, який має бути на слайді для класу, почни з «[слайд] ». На слайд став лише головне: 1–3 короткі рядки або одне зображення на крок.
8. Рядок лише для вчителя почни з «Для вчителя: ». Сюди — очікувані відповіді, типові помилки, методичні поради, критерії «готово, якщо».
9. Підказку для учня пиши рядком «Підказка: …», допомогу для тих, кому важко, — «Допомога: …», додаткове завдання — «Більше: …».
10. Зображення — рядком «![опис](https://адреса)», лише якщо в матеріалі є https-адреса. Схему або малюнок без адреси заміни рядком «Для вчителя: Схема: <що на ній зображено>».
11. Посилання — рядком «[текст](https://адреса)».
12. Питання з вибором відповіді: рядок «? питання», під ним без порожніх рядків варіанти «+ правильний» і «- неправильний» (2–6 варіантів, рівно один «+»), потім «= пояснення», якщо воно є в матеріалі.
13. Правда чи ні: «? Правда чи ні?», під ним рядки «Правда: …» і «Неправда: …».
14. Розподіл по групах: «? інструкція», під ним рядки «[Назва групи] предмет» (2–4 групи).
15. Правильні відповіді бери лише з матеріалу. Якщо відповіді в матеріалі немає, не роби завдання з «?»: напиши питання звичайним рядком, а під ним «Для вчителя: відповідь не вказана в матеріалі».

Приклад формату:

${LESSON_TEXT_EXAMPLE}`
